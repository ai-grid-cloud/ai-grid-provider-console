export const setupDefaults = (configuration: UseK8sNameDescriptionDataConfiguration): K8sNameDescriptionFieldData => {
  const { initialData, editableK8sName } = configuration;
  const name = initialData?.name ?? '';
  const value = initialData?.k8sName ?? '';
  const data: K8sNameDescriptionFieldData = {
    name,
    description: initialData?.description ?? '',
    k8sName: {
      value,
      state: {
        immutable: !!value && !editableK8sName,
        invalidCharacters: false,
        invalidLength: false,
        maxLength: configuration.maxLength ?? 253,
        routeNameTooLong: false,
        touched: !!editableK8sName && !!value && value !== translateDisplayNameForK8s(name),
        regexp: configuration.regexp,
        invalidCharsMessage: configuration.invalidCharsMessage,
        safePrefix: configuration.safePrefix,
        staticPrefix: configuration.staticPrefix,
      },
    },
  };
  return handleUpdateLogic(data)('name', name);
};
export const handleUpdateLogic =
  (
    existing: K8sNameDescriptionFieldData,
    _options?: { namespace?: string },
  ): K8sNameDescriptionFieldUpdateFunctionInternal =>
  (key, value) => {
    const data = { ...existing, k8sName: { ...existing.k8sName, state: { ...existing.k8sName.state } } };
    if (key === 'description') data.description = value;
    if (key === 'name') {
      data.name = value;
      if (!data.k8sName.state.touched && !data.k8sName.state.immutable) {
        data.k8sName.value = translateDisplayNameForK8s(value, {
          maxLength: data.k8sName.state.maxLength,
          safeK8sPrefix: data.k8sName.state.safePrefix,
          staticPrefix: data.k8sName.state.staticPrefix,
        });
      }
    }
    if (key === 'k8sName' && !data.k8sName.state.immutable) {
      data.k8sName.value = value;
      data.k8sName.state.touched = true;
    }
    data.k8sName.state.invalidCharacters =
      !!data.k8sName.value && !isValidK8sName(data.k8sName.value, data.k8sName.state.regexp);
    data.k8sName.state.invalidLength = data.k8sName.value.length > data.k8sName.state.maxLength;
    return data;
  };
export const isK8sNameDescriptionDataValid = (data: K8sNameDescriptionFieldData): boolean =>
  !!data.name.trim() &&
  isValidK8sName(data.k8sName.value, data.k8sName.state.regexp) &&
  !data.k8sName.state.invalidCharacters &&
  !data.k8sName.state.invalidLength;
