#!/usr/bin/env node
// Writes the golden output of the PoC's demoMetrics for the console's fixture clusters,
// which pins the Go port (bff/internal/fakebackend/demometrics.go) and the TypeScript port
// (frontend/src/services/demoMetrics.ts) to the PoC's numbers.
//
//   node hack/demo-metrics-golden.mjs <PoC>/shared/grid-monitoring.mjs > mock/golden/demo-metrics.json
//
// Argument 1 is the PoC's shared/grid-monitoring.mjs (krisv/ai-grid-cloud-provider-poc at
// 62319b8). The script imports it from where it is, reads mock/fixtures/managedclusters.json
// and writes only to stdout; nothing in the PoC is written.
//
// The input is what GetOverview passes to demoMetrics: the AI Grid members (label
// ai-grid/enabled=true), with the PoC's status from ManagedClusterConditionAvailable.
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const [source] = process.argv.slice(2);
if (!source) {
  console.error('usage: node hack/demo-metrics-golden.mjs <path to the PoC shared/grid-monitoring.mjs>');
  process.exit(2);
}

const START = 1790000000;
const END = START + 3600;
const STEP = 60;

const { demoMetrics } = await import(pathToFileURL(resolve(source)).href);
const fixtures = JSON.parse(
  await readFile(new URL('../mock/fixtures/managedclusters.json', import.meta.url), 'utf8'),
);

const status = (cluster) => {
  const available = cluster.status?.conditions?.find((c) => c.type === 'ManagedClusterConditionAvailable');
  if (available?.status === 'CONDITION_STATUS_TRUE') return 'Ready';
  if (available?.status === 'CONDITION_STATUS_FALSE') return 'Offline';
  return 'Unknown';
};

const clusters = fixtures.clusters
  .filter((c) => c.labels?.['ai-grid/enabled'] === 'true')
  .map((c) => ({ name: c.name, status: status(c), aiGridEnabled: true, site: c.labels['ai-grid/site'] }));

const golden = {
  _comment:
    'Generated by hack/demo-metrics-golden.mjs from krisv/ai-grid-cloud-provider-poc shared/grid-monitoring.mjs demoMetrics at 62319b8. Do not edit; regenerate.',
  input: { clusters: clusters.map(({ name, status }) => ({ name, status })), start: START, end: END, step: STEP },
  metrics: demoMetrics(clusters, START, END, STEP),
};
process.stdout.write(`${JSON.stringify(golden, null, 2)}\n`);
